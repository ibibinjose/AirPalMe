import type { BirthdayOffer } from "./birthday-freebies";

export type BirthdayOfferSeed = Omit<
  BirthdayOffer,
  "id" | "ownerUid" | "createdAt" | "updatedAt" | "createdBy"
> & { seedKey: string };

const DISCLAIMER_HINT =
  "Join the brand rewards programme before your birthday month. Terms vary; confirm in-store or in-app.";

function seed(
  partial: Omit<BirthdayOfferSeed, "status" | "ownerType" | "adultOnly" | "editorial" | "featured" | "description"> & {
    description?: string;
    adultOnly?: boolean;
    featured?: boolean;
  },
): BirthdayOfferSeed {
  return {
    ...partial,
    status: "live",
    ownerType: "admin",
    adultOnly: partial.adultOnly ?? true,
    editorial: true,
    featured: partial.featured ?? false,
    description: partial.description || DISCLAIMER_HINT,
  };
}

